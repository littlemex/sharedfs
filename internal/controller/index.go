// releasePollInterval is how often a release in progress is rechecked when no watch event is
// guaranteed to report its next step.
const releasePollInterval = 5 * time.Second

const (
	// indexClaimFilesystem indexes SharedFilesystemClaims by the SharedFilesystem they name.
	indexClaimFilesystem = ".spec.filesystemRef.name"
	// indexFilesystemSource indexes SharedFilesystems by their source PersistentVolume.
	indexFilesystemSource = ".spec.source.persistentVolumeName"
)

// SetupIndexes registers the field indexes the reconcilers list by.
func SetupIndexes(ctx context.Context, mgr ctrl.Manager) error {
	idx := mgr.GetFieldIndexer()
	if err := idx.IndexField(ctx, &sharedfsv1alpha1.SharedFilesystemClaim{}, indexClaimFilesystem,
		func(o client.Object) []string {
			return []string{o.(*sharedfsv1alpha1.SharedFilesystemClaim).Spec.FilesystemRef.Name}
		}); err != nil {
		return err
	}
	return idx.IndexField(ctx, &sharedfsv1alpha1.SharedFilesystem{}, indexFilesystemSource,
		func(o client.Object) []string {
			return []string{o.(*sharedfsv1alpha1.SharedFilesystem).Spec.Source.PersistentVolumeName}
		})
}

// isGenerated reports whether a PersistentVolume was generated by sharedfs.
func isGenerated(o client.Object) bool {
	return o.GetLabels()[volume.LabelManagedBy] == volume.ManagedByValue
}

// claimOfPV maps a generated PersistentVolume to the claim it was generated for.
func claimOfPV(pv client.Object) (types.NamespacedName, types.UID, bool) {
	ns := pv.GetLabels()[volume.LabelClaimNamespace]
	name := pv.GetAnnotations()[volume.AnnotationClaimName]
	uid := types.UID(pv.GetLabels()[volume.LabelClaimUID])
	if !isGenerated(pv) || ns == "" || name == "" || uid == "" {
		return types.NamespacedName{}, "", false
	}
	return types.NamespacedName{Namespace: ns, Name: name}, uid, true
}

func requests(names ...types.NamespacedName) []reconcile.Request {
	out := make([]reconcile.Request, 0, len(names))
	for _, n := range names {
		out = append(out, reconcile.Request{NamespacedName: n})
	}
	return out
}

// setCondition sets a condition stamped with the object's generation.
func setCondition(conds *[]metav1.Condition, generation int64, typ string, ok bool, reason, msg string) {
	status := metav1.ConditionFalse
	if ok {
		status = metav1.ConditionTrue
	}
	meta.SetStatusCondition(conds, metav1.Condition{
		Type: typ, Status: status, Reason: reason, Message: msg, ObservedGeneration: generation,
	})
}

// pvcOf returns the PVC a generated PV is reserved for.
func pvcOf(pv *corev1.PersistentVolume) (types.NamespacedName, bool) {
	if pv.Spec.ClaimRef == nil {
		return types.NamespacedName{}, false
	}
	return types.NamespacedName{Namespace: pv.Spec.ClaimRef.Namespace, Name: pv.Spec.ClaimRef.Name}, true
}
