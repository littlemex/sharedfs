package volume

import (
	"fmt"
	"strings"

	corev1 "k8s.io/api/core/v1"

	sharedfsv1alpha1 "github.com/littlemex/sharedfs/api/v1alpha1"
	"github.com/littlemex/sharedfs/internal/driver"
)

// SourceError is a reason a source PersistentVolume cannot be distributed.
type SourceError struct {
	Reason  string
	Message string
}

func (e *SourceError) Error() string { return e.Reason + ": " + e.Message }

// Resolve copies the allow-listed fields of a source PersistentVolume. Annotations (for example
// pv.kubernetes.io/provisioned-by) and the reclaim policy are never copied: generated volumes
// are always Retain, so deleting one never asks the driver to delete the file system.
func Resolve(pv *corev1.PersistentVolume) (*sharedfsv1alpha1.ResolvedSource, error) {
	if pv.Labels[LabelManagedBy] == ManagedByValue {
		return nil, &SourceError{sharedfsv1alpha1.ReasonSourceIsGenerated,
			fmt.Sprintf("%s was generated by sharedfs; name the original PersistentVolume instead", pv.Name)}
	}
	csi := pv.Spec.CSI
	if csi == nil {
		return nil, &SourceError{sharedfsv1alpha1.ReasonSourceNotCSI,
			fmt.Sprintf("%s is not a CSI volume", pv.Name)}
	}
	p, ok := driver.Lookup(csi.Driver)
	if !ok {
		return nil, &SourceError{sharedfsv1alpha1.ReasonUnsupportedDriver,
			fmt.Sprintf("driver %q is not supported; supported: %s", csi.Driver, strings.Join(driver.Names(), ", "))}
	}
	if csi.VolumeHandle == "" {
		return nil, &SourceError{sharedfsv1alpha1.ReasonInvalidSource, fmt.Sprintf("%s has no volumeHandle", pv.Name)}
	}
	// The longest generated handle is the source handle plus "-sfc-" and a 36-byte UID.
	if n := len(csi.VolumeHandle) + len("-sfc-") + 36; n > MaxVolumeHandleBytes {
		return nil, &SourceError{sharedfsv1alpha1.ReasonInvalidSource,
			fmt.Sprintf("volumeHandle %q leaves no room for a per-claim suffix (%d > %d bytes)", csi.VolumeHandle, n, MaxVolumeHandleBytes)}
	}
	capacity, ok := pv.Spec.Capacity[corev1.ResourceStorage]
	if !ok {
		return nil, &SourceError{sharedfsv1alpha1.ReasonInvalidSource, fmt.Sprintf("%s has no storage capacity", pv.Name)}
	}
	return &sharedfsv1alpha1.ResolvedSource{
		UID:              pv.UID,
		Driver:           csi.Driver,
		VolumeHandle:     csi.VolumeHandle,
		VolumeAttributes: p.CopyAttributes(csi.VolumeAttributes),
		MountOptions:     p.NormalizeMountOptions(pv.Spec.MountOptions),
		Capacity:         capacity.String(),
	}, nil
}
