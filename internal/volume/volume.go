// Package volume builds the PersistentVolume and PersistentVolumeClaim that one
// SharedFilesystemClaim stands for, and answers which existing objects belong to which claim.
//
// It is pure: no client calls, so every rule here is unit-testable.
package volume

import (
	"maps"
	"slices"
	"strings"

	corev1 "k8s.io/api/core/v1"
	"k8s.io/apimachinery/pkg/api/resource"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"k8s.io/apimachinery/pkg/types"
	corev1ac "k8s.io/client-go/applyconfigurations/core/v1"
	"k8s.io/utils/ptr"

	sharedfsv1alpha1 "github.com/littlemex/sharedfs/api/v1alpha1"
)

// FieldOwner is the server-side apply field manager for generated PersistentVolumes.
const FieldOwner = "sharedfs"

const (
	// pvNamePrefix starts every generated PersistentVolume name, followed by the claim UID.
	pvNamePrefix = "sfc-"
	// handleSuffix joins the source handle and the claim UID in a generated volumeHandle.
	handleSuffix = "-sfc-"
	// maxCSIVolumeIDBytes is the CSI limit on a volume ID.
	maxCSIVolumeIDBytes = 128
	// uidBytes is the length of a Kubernetes UID in its canonical form (a UUID).
	uidBytes = 36
	// MaxSourceHandleBytes is the longest source handle that still fits once suffixed.
	MaxSourceHandleBytes = maxCSIVolumeIDBytes - len(handleSuffix) - uidBytes

	mountOptionReadOnly  = "ro"
	mountOptionReadWrite = "rw"
)

// requestedStorage is what a generated PVC asks for, capped at the source capacity. A static
// PersistentVolume binds when its capacity covers the request, so a small request binds while
// keeping the tenant's storage ResourceQuota from being charged the whole file system.
var requestedStorage = resource.MustParse("1Gi")

// PVName is the generated PersistentVolume name. It comes from the claim UID so two claims can
// never map to one name ("a-b"+"c" and "a"+"b-c" would with a joined name), and so the claim UID
// can be read back from the name, which only cluster admins can change.
func PVName(claimUID types.UID) string { return pvNamePrefix + string(claimUID) }

// ClaimUIDOf reads the claim UID back from a generated PersistentVolume name.
func ClaimUIDOf(pvName string) (types.UID, bool) {
	uid, ok := strings.CutPrefix(pvName, pvNamePrefix)
	return types.UID(uid), ok && len(uid) == uidBytes
}

// IsGenerated reports whether a PersistentVolume or PersistentVolumeClaim was generated by
// sharedfs.
func IsGenerated(o metav1.Object) bool {
	_, ok := o.GetLabels()[sharedfsv1alpha1.LabelClaimUID]
	return ok
}

// PV builds the server-side apply configuration of the PersistentVolume for a claim.
//
// claimRef carries the namespace and name only. The PV controller owns uid and resourceVersion;
// leaving them out lets the claimRef reserve the volume for exactly this PVC without fighting the
// binder over the fields it writes (claimRef is a granular struct for server-side apply).
func PV(claim *sharedfsv1alpha1.SharedFilesystemClaim, fs *sharedfsv1alpha1.SharedFilesystem, src *Source) *corev1ac.PersistentVolumeApplyConfiguration {
	opts := slices.Clone(src.MountOptions)
	if claim.Spec.Access != sharedfsv1alpha1.AccessReadWrite {
		opts = append(opts, mountOptionReadOnly)
	}
	return corev1ac.PersistentVolume(PVName(claim.UID)).
		WithLabels(map[string]string{
			sharedfsv1alpha1.LabelClaimUID:      string(claim.UID),
			sharedfsv1alpha1.LabelFilesystemUID: string(fs.UID),
		}).
		WithAnnotations(map[string]string{sharedfsv1alpha1.AnnotationFilesystemName: fs.Name}).
		WithSpec(corev1ac.PersistentVolumeSpec().
			WithCapacity(corev1.ResourceList{corev1.ResourceStorage: src.Capacity}).
			WithAccessModes(src.Profile.AccessMode).
			WithPersistentVolumeReclaimPolicy(corev1.PersistentVolumeReclaimRetain).
			WithStorageClassName("").
			WithVolumeMode(corev1.PersistentVolumeFilesystem).
			WithMountOptions(opts...).
			WithCSI(corev1ac.CSIPersistentVolumeSource().
				WithDriver(src.Profile.Name).
				// Its own handle per PV: kubelet identifies a CSI volume by driver and handle,
				// so two PVs with one handle collide on a node. Resolve bounds the length.
				WithVolumeHandle(src.VolumeHandle + handleSuffix + string(claim.UID)).
				WithVolumeAttributes(maps.Clone(src.VolumeAttributes))).
			WithClaimRef(corev1ac.ObjectReference().
				WithKind("PersistentVolumeClaim").
				WithAPIVersion("v1").
				WithNamespace(claim.Namespace).
				WithName(claim.Name)))
}

// KeepCSI makes desired keep the CSI source of an existing volume: a PersistentVolume's volume
// source cannot change, and the mutable fields (mount options, claimRef) must still be applied.
func KeepCSI(desired *corev1ac.PersistentVolumeApplyConfiguration, existing *corev1.PersistentVolume) {
	desired.Spec.CSI = corev1ac.CSIPersistentVolumeSource().
		WithDriver(existing.Spec.CSI.Driver).
		WithVolumeHandle(existing.Spec.CSI.VolumeHandle).
		WithVolumeAttributes(maps.Clone(existing.Spec.CSI.VolumeAttributes))
}

// PVC builds the PersistentVolumeClaim for a claim, named after the claim. It is created once
// and never updated: nothing in its spec changes after creation.
func PVC(claim *sharedfsv1alpha1.SharedFilesystemClaim, src *Source) *corev1.PersistentVolumeClaim {
	request := requestedStorage
	if src.Capacity.Cmp(request) < 0 {
		request = src.Capacity
	}
	return &corev1.PersistentVolumeClaim{
		ObjectMeta: metav1.ObjectMeta{
			Name:      claim.Name,
			Namespace: claim.Namespace,
			Labels:    map[string]string{sharedfsv1alpha1.LabelClaimUID: string(claim.UID)},
		},
		Spec: corev1.PersistentVolumeClaimSpec{
			AccessModes: []corev1.PersistentVolumeAccessMode{src.Profile.AccessMode},
			// "" and not nil: on a cluster with a default StorageClass, nil lets the
			// DefaultStorageClass admission plugin set that class, which then differs from the
			// generated PV's "" and the two do not bind.
			StorageClassName: ptr.To(""),
			VolumeName:       PVName(claim.UID),
			VolumeMode:       ptr.To(corev1.PersistentVolumeFilesystem),
			Resources: corev1.VolumeResourceRequirements{
				Requests: corev1.ResourceList{corev1.ResourceStorage: request},
			},
		},
	}
}

// OwnsPVC reports whether pvc belongs to the claim with this UID. The test reads volumeName,
// which the binder treats as authoritative and which cannot reach anything the claim is not
// granted: the generated PV is reserved for this namespace and name by its claimRef.
// ownerReferences and labels are not used because the tenant can edit them.
func OwnsPVC(claimUID types.UID, pvc *corev1.PersistentVolumeClaim) bool {
	return pvc.Spec.VolumeName == PVName(claimUID)
}

// CSIDrift lists the CSI fields of an existing PV that differ from the desired ones. A
// difference means the source changed under the claim.
func CSIDrift(existing *corev1.PersistentVolume, desired *corev1ac.PersistentVolumeApplyConfiguration) []string {
	have, want := existing.Spec.CSI, desired.Spec.CSI
	if have == nil {
		return []string{"csi"}
	}
	var drift []string
	if have.Driver != *want.Driver {
		drift = append(drift, "csi.driver")
	}
	if have.VolumeHandle != *want.VolumeHandle {
		drift = append(drift, "csi.volumeHandle")
	}
	if !maps.Equal(have.VolumeAttributes, want.VolumeAttributes) {
		drift = append(drift, "csi.volumeAttributes")
	}
	return drift
}

// StaleClaimUID reports the "Released" trap: a Retain PV still holding the UID of a PVC that was
// deleted and recreated under the same name. Only then is claimRef.uid cleared. A Bound PV is
// never touched, whatever the PVC read says.
func StaleClaimUID(pv *corev1.PersistentVolume, livePVC *corev1.PersistentVolumeClaim) bool {
	return pv.Status.Phase == corev1.VolumeReleased &&
		pv.Spec.ClaimRef != nil &&
		pv.Spec.ClaimRef.UID != "" &&
		livePVC != nil &&
		livePVC.DeletionTimestamp == nil &&
		pv.Spec.ClaimRef.UID != livePVC.UID
}
